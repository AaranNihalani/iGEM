# Figure 4 – model quality: bootstrap CIs + composition baseline
# ============================================================

def fig_model_quality():
    ci_df   = pd.read_csv(OUTDIR / 'bootstrap_ci.csv')
    base_df = pd.read_csv(OUTDIR / 'composition_baseline.csv')

    fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))

    proteases = ['MMP-2', 'MMP-9', 'NE']
    colours   = [PALETTE[p] for p in proteases]

    # Parse CI strings
    def parse_ci(s):
        s = s.strip('[]')
        lo, hi = s.split(',')
        return float(lo), float(hi)

    aurocs = ci_df['auroc'].values
    ci_lo  = np.array([parse_ci(ci_df.loc[ci_df['protease'] == p, 'auroc_95ci'].values[0])[0]
                       for p in proteases])
    ci_hi  = np.array([parse_ci(ci_df.loc[ci_df['protease'] == p, 'auroc_95ci'].values[0])[1]
                       for p in proteases])
    err_lo = aurocs - ci_lo
    err_hi = ci_hi - aurocs

    # Left: AUROC with 95% CI error bars
    ax = axes[0]
    x = np.arange(3)
    bars = ax.bar(x, aurocs, 0.5, color=colours, edgecolor='white', linewidth=0.6, alpha=0.85)
    ax.errorbar(x, aurocs, yerr=[err_lo, err_hi], fmt='none',
                color='black', capsize=5, lw=1.8, capthick=1.8)

    for bar, v in zip(bars, aurocs):
        ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height() + 0.005,
                f'{v:.3f}', ha='center', va='bottom', fontsize=9.5, fontweight='bold')

    ax.axhline(0.5, color='grey', lw=0.9, linestyle='--', label='Random (0.5)')
    ax.axhline(0.8, color='steelblue', lw=0.7, linestyle=':', alpha=0.6, label='0.8 reference')
    ax.set_xticks(x)
    ax.set_xticklabels(proteases, fontsize=11)
    ax.set_ylabel('AUROC (5-fold CV)', fontsize=10)
    ax.set_title('AUROC with bootstrapped 95% CI\n(1,000 iterations)',
                 fontsize=9.5, fontweight='bold')
    ax.set_ylim(0.3, 1.0)
    ax.legend(fontsize=8)
    ax.grid(axis='y', alpha=0.3)
    ax.spines['top'].set_visible(False)
    ax.spines['right'].set_visible(False)

    # Right: VHSE8 vs bag-of-AAs
    ax2 = axes[1]
    vhse8 = base_df['auroc_vhse8'].values
    bag   = base_df['auroc_bag_of_aas'].values
    width = 0.3

    b1 = ax2.bar(x - width / 2, vhse8, width, label='VHSE8 + LR (positional)',
                 color=colours, edgecolor='white', linewidth=0.6, alpha=0.9)
    b2 = ax2.bar(x + width / 2, bag, width, label='Bag-of-AAs + LR (no position)',
                 color=colours, edgecolor='black', linewidth=0.8, alpha=0.4, hatch='//')

    for i, (v, b) in enumerate(zip(vhse8, bag)):
        delta = v - b
        mid_x = x[i]
        max_y = max(v, b) + 0.025
        ax2.annotate(f'Δ={delta:+.3f}', xy=(mid_x, max_y),
                     ha='center', fontsize=8.5, fontweight='bold',
                     color=PALETTE[proteases[i]])

    ax2.axhline(0.5, color='grey', lw=0.9, linestyle='--')
    ax2.set_xticks(x)
    ax2.set_xticklabels(proteases, fontsize=11)
    ax2.set_ylabel('AUROC (5-fold CV)', fontsize=10)
    ax2.set_title('VHSE8 vs composition-only baseline\n(positional encoding contribution)',
                  fontsize=9.5, fontweight='bold')
    ax2.set_ylim(0.3, 1.0)
    ax2.legend(fontsize=8)
    ax2.grid(axis='y', alpha=0.3)
    ax2.spines['top'].set_visible(False)
    ax2.spines['right'].set_visible(False)

    fig.tight_layout(pad=2.0)
    out = FIGDIR / 'fig_model_quality.png'
    fig.savefig(out, dpi=180, bbox_inches='tight')
    plt.close(fig)
    print(f'Saved {out}')


if __name__ == '__main__':
    fig_heatmap()
    fig_candidate_scores()
    fig_model_quality()
    print('All figures generated.')
