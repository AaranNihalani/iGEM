# Figure 2 – 3×3 specificity matrix heatmap
# ============================================================

def fig_heatmap():
    normed = pd.read_csv(OUTDIR / 'specificity_matrix_3plex_normalised.csv', index_col=0)

    # Rename rows/cols for display
    row_labels = {'MMP-2': 'MMP-2\n(PLGLAGQS)', 'MMP-9': 'MMP-9\n(PRSLSGLK)', 'NE': 'NE\n(AAPVSGIG)'}
    col_labels  = {'MMP-2': 'Cand 2\n(MMP-2 target)', 'MMP-9': 'Cand 1\n(MMP-9 target)', 'NE': 'Cand 4\n(NE target)'}

    mat = normed.rename(index=row_labels, columns=col_labels)

    fig, ax = plt.subplots(figsize=(6.5, 4.8))
    norm = TwoSlopeNorm(vmin=-2.5, vcenter=0, vmax=1.0)
    cmap = plt.cm.RdYlGn
    im = ax.imshow(mat.values, cmap=cmap, norm=norm, aspect='auto')

    ax.set_xticks(range(len(mat.columns)))
    ax.set_xticklabels(mat.columns, fontsize=9)
    ax.set_yticks(range(len(mat.index)))
    ax.set_yticklabels(mat.index, fontsize=9)
    ax.set_xlabel('Substrate candidate (scored)', fontsize=10)
    ax.set_ylabel('Protease PSSM (scorer)', fontsize=10)

    for i in range(len(mat.index)):
        for j in range(len(mat.columns)):
            val = mat.values[i, j]
            colour = 'white' if abs(val) > 1.5 else 'black'
            weight = 'bold' if i == j else 'normal'
            flag   = '*' if i != j and val >= 0.20 else ''
            ax.text(j, i, f'{val:.2f}{flag}', ha='center', va='center',
                    fontsize=11, color=colour, fontweight=weight)

        # Diagonal outline
        ax.add_patch(plt.Rectangle((i - 0.5, i - 0.5), 1, 1,
                                    fill=False, edgecolor='black', lw=2))

    cb = fig.colorbar(im, ax=ax, fraction=0.035, pad=0.04)
    cb.set_label('Normalised cross-reactivity score', fontsize=9)

    ax.set_title('3-plex specificity matrix  (κ = 98.1 → poorly conditioned)',
                 fontsize=11, fontweight='bold', pad=10)
    fig.text(0.99, 0.01,
             '* flagged ≥ 0.20  |  diagonal = self-score reference (±1.0)',
             ha='right', fontsize=7.5, color=GREY, style='italic')

    fig.tight_layout()
    out = FIGDIR / 'fig_3plex_heatmap.png'
    fig.savefig(out, dpi=180, bbox_inches='tight')
    plt.close(fig)
    print(f'Saved {out}')


